const assert = require('assert/strict')
const { createHealthState } = require('./health-state')
let time = 1
const health = createHealthState({ now: () => time })
health.success('scan', { cursor: 'abc' })
time++
health.failure('mail', new Error('Authentication failed for private@example.test'), { queued: 10 })
health.observe('mail', { queued: 11, ok: true })
assert.equal(health.get('mail').ok, false)
assert.equal(health.get('mail').consecutiveFailures, 1)
assert.equal(health.get('mail').lastFailureAt, 2)
assert.equal(health.get('mail').queued, 11)
assert.equal(JSON.stringify(health.status()).includes('private@example.test'), false)
health.failure('mail', { code: 'EAUTH', message: 'secret' })
assert.equal(health.get('mail').error, 'EAUTH')
assert.equal(health.get('mail').consecutiveFailures, 2)
assert.equal(health.get('scan').ok, true)
time++
health.success('mail', { queued: 0 })
assert.equal(health.get('mail').lastSuccessAt, 3)
assert.equal(health.get('mail').consecutiveFailures, 0)
assert.equal(health.get('mail').error, null)
assert.equal(health.get('mail').lastFailureAt, 2)
console.log('health state tests passed')
